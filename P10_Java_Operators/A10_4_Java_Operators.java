package P10_Java_Operators;
public class A10_4_Java_Operators {
    public static void main(String[] args) {
        int nota = 16;
        int notaMinima = 14;
        System.out.println(nota == notaMinima);
        System.out.println(nota != notaMinima);
        System.out.println(nota >= notaMinima);
    }
}