package P7_Java_Variables;
public class A7_2_Java_Variables {
    public static void main(String[] args) {
        String nombre = "Ana";
        int edad = 18;
        int anios = 2;
        System.out.println(nombre);
        System.out.println("Edad actual: " + edad);
        System.out.println("Edad en dos años: " + (edad + anios));
    }
}